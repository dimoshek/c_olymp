/* Задание. Солдат хочет купить w бананов: i-й банан стоит i*k долларов.
У него есть n долларов. Найти, сколько долларов ему нужно занять.
Если денег хватает, вывести 0. */
#include <stdio.h>

int main() {
    /* k - цена первого банана, n - деньги солдата, w - количество бананов */
    int k, n, w;
    /* sum - общая стоимость всех бананов */
    int sum = 0;
    int res;
    int i;

    scanf("%d %d %d", &k, &n, &w);

    /* Подсчет общей стоимости: k + 2k + ... + w*k */
    for (i = 1; i <= w; ++i) {
        sum = sum + i * k;
    }

    /* Сколько не хватает денег */
    res = sum - n;

    /* Если денег хватает, занимать не нужно */
    if (res < 0) {
        res = 0;
    }

    /* Вывод результата */
    printf("%d", res);

    return 0;
}