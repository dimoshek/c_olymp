/* Задание. Вывести максимальное количество доминошек (2x1), помещающихся на доске */
#include <stdio.h>
int main() {
    int m, n;
    int pole, fill;
    scanf("%d %d", &m, &n);
    /* Площадь доски */
    pole = m * n;
    /* Каждая доминошка занимает 2 клетки */
    fill = pole / 2;
    /* Печать */
    printf("%d", fill);

    return 0;
}
