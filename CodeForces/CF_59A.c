/* Задание. Если в слове строго больше заглавных букв - привести его
к верхнему регистру, иначе - к нижнему. */
#include <stdio.h>
#include <ctype.h>
#define MAXN 105

int main() {
    char word[MAXN];
    /* cap - количество заглавных букв, low - количество строчных */
    int cap = 0;
    int low = 0;
    int i;

    scanf("%s", word);

    /* Подсчет заглавных и строчных букв.
    Коды заглавных (65-90) меньше кодов строчных (97-122) */
    for (i = 0; word[i] != '\0'; ++i) {
        if (word[i] < 96) {
            ++cap;
        }
        else {
            ++low;
        }
    }

    /* Заглавных строго больше - приводим к верхнему регистру */
    if (cap > low) {
        for (i = 0; word[i] != '\0'; ++i) {
            word[i] = toupper(word[i]);
        }
    }
    /* Иначе (в том числе при равенстве) - к нижнему регистру */
    else {
        for (i = 0; word[i] != '\0'; ++i) {
            word[i] = tolower(word[i]);
        }
    }

    /* Вывод результата */
    printf("%s", word);

    return 0;
}