/* Задание. Найти минимальное количество камней, которые нужно убрать,
чтобы любые два соседних камня имели разные цвета. */
#include <stdio.h>
#define MAXN 105

int main() {
    int n;
    char kam[MAXN];
    /* pred - цвет предыдущего камня */
    char pred;
    int res = 0;
    int i;

    scanf("%d", &n);
    /* Чтение первого камня (пробел пропускает перевод строки) */
    scanf(" %c", &kam[0]);
    pred = kam[0];

    /* Подсчет соседних камней одного цвета */
    for (i = 1; i < n; ++i) {
        scanf(" %c", &kam[i]);
        if (kam[i] == pred) {
            ++res;
        }
        pred = kam[i];
    }

    /* Вывод результата */
    printf("%d", res);

    return 0;
}